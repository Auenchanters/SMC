// Writes CALCULATIONS.md from model.mjs: every number DESIGN.md quotes, recomputed.
// Run from the repository root: node hardware/rover-v2/calc.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  BATTERY, BMS, CELL, CG, CLEAN, CYCLES_PER_DAY, DIM, MASS, OVERALL, PACK, POWER, PUSH_SAFETY, SERVICE,
  SOIL, STABILITY, STROKE, TOTAL_KG, TRACTION, WEIGHT_N, WET_CLEAN_S, availableForce, cycle,
  insertionForce, surveyEnergy, tyrePressureKPa,
} from "./model.mjs";

const n = (v, d = 0) => v.toFixed(d);
const rows = (head, list) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...list.map((r) => `| ${r.join(" | ")} |`)].join("\n");

const c = cycle();
const e = surveyEnergy();
const moist = insertionForce("moist");
const dry = insertionForce("dry");
const out = [];
out.push(`# AgriRover v2: calculations

Generated by \`node hardware/rover-v2/calc.mjs\` from [model.mjs](model.mjs). Do not edit by hand. Numbers marked [A] in the model are assumptions to confirm on the bench, so every result here is a design estimate, not a measurement.

## Size

| | mm |
|---|---|
| Overall length (camera beam to rear tyre) | ${n(OVERALL.length)} |
| Overall width over the tyres | ${n(OVERALL.width)} |
| Height (GNSS antenna top; the probe axis is ${DIM.tower.z1}) | ${n(OVERALL.height)} |
| Wheelbase / track | ${DIM.wheel.base} / ${DIM.wheel.track} |
| Wheel diameter | ${2 * DIM.wheel.r} |
| Belly clearance (body) / rocker beam clearance | ${OVERALL.belly} / ${OVERALL.beamClearance} |
| Probe stroke (parked tips ${DIM.probe.tip0} above ground, ${DIM.probe.depth} deep, ${DIM.probe.groundSlack} for a lower surface) | ${STROKE} |

## Mass and centre of mass

${rows(["Part", "kg", "x", "z"], MASS.map((m) => [m[0], n(m[1], 1), n(m[2]), n(m[4])]))}
| **Total** | **${n(TOTAL_KG, 1)}** | **${n(CG[0])}** | **${n(CG[2])}** |

Weight ${n(WEIGHT_N)} N. The centre of mass is ${n(Math.abs(CG[0]), 1)} mm ${CG[0] >= 0 ? "ahead of" : "behind"} the probe axis and ${n(CG[2])} mm above the ground.

## Stability

| | |
|---|---|
| Side slope before tipping (static) | ${n(STABILITY.rollDeg)} deg |
| Slope up or down before tipping (static) | ${n(STABILITY.pitchDeg)} deg |
| A ${STABILITY.stepMm} mm step under one wheel | that beam tilts ${n(STABILITY.beamTiltDeg)} deg, the body only ${n(STABILITY.bodyPitchDeg, 1)} deg; all four wheels stay loaded |
| Braking needed to tip it forward | ${n(STABILITY.tipDecelG, 2)} g (stopping from 0.5 m/s in 0.25 s is 0.2 g) |

## Probe force

Pushing the probe down pushes the rover up (Newton's third law), so the push is limited by the weight that holds the rover down. The probe sits on the rocker pivot line, so the reaction is shared by all four wheels.

${rows(["", "N"], [
  [`Needed, moist soil (${SOIL.coneMPa.moist} MPa tip, ${SOIL.shaftKPa.moist} kPa sleeve, ${DIM.probe.depth} mm)`, n(moist)],
  [`Needed, dry crust (${SOIL.coneMPa.dry} MPa, ${SOIL.shaftKPa.dry} kPa)`, n(dry)],
  ["Available, probe centred (lift-off)", n(availableForce(0))],
  [`Usable, probe centred (${PUSH_SAFETY * 100}% of lift-off)`, n(PUSH_SAFETY * availableForce(0))],
  [`Usable, probe ${DIM.probeRail.y} mm to one side`, n(PUSH_SAFETY * availableForce(DIM.probeRail.y))],
  ["v1 for comparison (usable lift-off at the rear axle)", "54"],
])}

Margin in dry soil with the probe centred: ${n((PUSH_SAFETY * availableForce(0)) / dry, 1)} x.

## Ground, traction and climbing

| | |
|---|---|
| Tyre pressure / ground pressure | about ${tyrePressureKPa} kPa (a person standing: 25 to 60 kPa) |
| Traction (drawbar pull, mu ${SOIL.mu}) | ${n(TRACTION.drawbarN)} N |
| Rolling resistance (soft tilled soil, ${SOIL.crr}) | ${n(TRACTION.rollingN)} N |
| Steepest grade it can climb | about ${n(TRACTION.maxGradeDeg)} deg |
| Step it can climb reliably (about half the wheel radius) | about ${n(TRACTION.stepMm)} mm; v1 about ${n(75 / 2)} mm |

## Probe cycle

${rows(["Step", "ends at (s)"], [
  ["Approach to the surface (time-of-flight finds it)", n(c.t1, 1)],
  [`Insert ${DIM.probe.depth} mm at ${6} mm/s`, n(c.t2, 1)],
  ["Read", n(c.t3, 1)],
  ["Retract through the wiper plate and brushes", n(c.t4, 1)],
  ["Air blast", n(c.t5, 1)],
  ["Air check (clean?)", n(c.t6, 1)],
])}

A wet clean, when the air check fails twice, adds ${n(WET_CLEAN_S)} s (${CLEAN.wetS} s water spray, ${CLEAN.dryS} s air dry, re-check). At ${CLEAN.wetShare * 100}% of cycles [A] the average cycle is ${n(c.t6 + CLEAN.wetShare * WET_CLEAN_S, 1)} s. The ${DIM.waterTank.ml} mL tank lasts ${n(DIM.waterTank.ml / CLEAN.wetMl / CLEAN.wetShare)} cycles, about ${n(DIM.waterTank.ml / CLEAN.wetMl / CLEAN.wetShare / CYCLES_PER_DAY, 1)} days at ${CYCLES_PER_DAY} cycles a day; the dock refills it after every mission.

## Battery and energy

| | |
|---|---|
| Pack | ${PACK.s}S${PACK.p}P ${CELL.chem}, ${CELL.ah} Ah cells: ${n(BATTERY.vNom, 1)} V nominal, ${n(BATTERY.wh)} Wh |
| Charge to / soft cut-off | ${n(BATTERY.vMax, 1)} V (${CELL.vChargeTo} V per cell) / ${n(BATTERY.vMin, 1)} V (${CELL.vCutSoft} V per cell) |
| Peak current (four motors at their ${POWER.motorLimitW} W limit) | ${n(POWER.peakA)} A; BMS limit ${BMS.ocContinuousA} A continuous, ${BMS.ocPeakA} A for ${BMS.ocPeakMs / 1000} s |

Energy for the simulator's seed-7 survey (466 m, 60 probes, 32 turns in place):

${rows(["Load", "Wh"], [...Object.entries(e.parts).map(([k, v]) => [k, n(v, 1)]), ["**Total**", `**${n(e.total, 1)}**`]])}

Mission time about ${n(e.missionS / 60)} min. Usable energy (${BATTERY.usableShare * 100}% of the pack) is ${n(BATTERY.wh * BATTERY.usableShare)} Wh: about **${n((BATTERY.wh * BATTERY.usableShare) / e.total, 1)} surveys per charge**. Charging at ${BMS.chargeA} A (0.5 C) from the return-to-dock level (${BMS.returnToDockSoc * 100}%) takes about ${n(((1 - BMS.returnToDockSoc) * CELL.ah) / BMS.chargeA, 1)} h.

## Power rails

${rows(["Rail", "From", "Feeds"], POWER.rails)}

## Wear parts and service

${rows(["Part", "Life [A]", "", "How"], SERVICE.map((s) => [s[0], String(s[1]), s[2], s[3]]))}

At ${CYCLES_PER_DAY} probe cycles a day, the wiper plate lasts about ${n(5000 / CYCLES_PER_DAY)} days and the brushes about ${n(10000 / CYCLES_PER_DAY)} days.
`);
const file = join(dirname(fileURLToPath(import.meta.url)), "CALCULATIONS.md");
writeFileSync(file, out.join("\n"));
console.log("wrote", file);
